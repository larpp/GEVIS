"""Official Transformers PatchTST models; only tensor interface adaptation.

No manual attention/layer traversal, interpolation, latent projection or local
statistics network. Public forecasting encoder is reused; the OFFICIAL masked
reconstruction head is newly initialized and trained in STEP 1.

The domain-v2 training objective lives in patchtst_adaptation: the same official
model/head forwards under externally blinded inputs, with added fidelity losses.
The stock pretraining_loss method remains available for baseline compatibility.
"""
from copy import deepcopy
import torch
from torch import nn
from .pretrained_patchtst import MODEL_ID,REVISION,PUBLIC_FILES_SHA256,checkpoint_hash

BACKEND='hf_patchtst_official_ssl_v1'
PATCH_LENGTH=12
HIDDEN_WIDTH=128


class OfficialPatchEncoder(nn.Module):
    def __init__(self,n_sensors,*,hf_config):
        super().__init__()
        from transformers import PatchTSTConfig,PatchTSTForPretraining,PatchTSTModel
        cfg=PatchTSTConfig(**hf_config)
        if cfg.num_input_channels!=1 or not cfg.share_embedding or cfg.channel_attention:
            raise ValueError('Official independent-channel configuration required')
        if cfg.patch_length!=cfg.patch_stride or cfg.context_length%cfg.patch_length:
            raise ValueError('Complete nonoverlapping official patches required')
        self.n_sensors=n_sensors;self.patch_len=cfg.patch_length;self.d_model=cfg.d_model
        self.hf=PatchTSTForPretraining(cfg)
        clean_cfg=deepcopy(cfg);clean_cfg.do_mask_input=False
        self.features=PatchTSTModel(clean_cfg)
        self.features.encoder=self.hf.model.encoder  # SAME official encoder weights.
        self.hf_config=cfg.to_dict()
        self.pretrained_identity=None

    @property
    def pretrained(self):return self.hf.model

    @property
    def decoder(self):return self.hf.head.linear  # Compatibility only; forward restores units.

    @classmethod
    def from_public(cls,path,n_sensors,window_length,*,mask_ratio=.5):
        from transformers import PatchTSTConfig,PatchTSTForPretraining
        identity=checkpoint_hash(path)
        if identity!=PUBLIC_FILES_SHA256:raise ValueError('Public PatchTST checkpoint hash mismatch')
        cfg=PatchTSTConfig.from_pretrained(str(path),local_files_only=True)
        if cfg.positional_encoding_type!='sincos':raise ValueError('Only fixed official positions may change')
        if not 0<mask_ratio<1:raise ValueError('Official masking ratio must be between 0 and 1')
        cfg.context_length=window_length;cfg.num_input_channels=1
        cfg.mask_type='random';cfg.random_mask_ratio=mask_ratio
        model=cls(n_sensors,hf_config=cfg.to_dict())
        loaded,info=PatchTSTForPretraining.from_pretrained(str(path),config=cfg,
            local_files_only=True,use_safetensors=True,ignore_mismatched_sizes=True,output_loading_info=True)
        allowed_missing={'head.linear.weight','head.linear.bias'}
        fixed_position='model.encoder.positional_encoder.position_enc'
        missing=set(info.get('missing_keys',[]))
        mismatched={item[0] if isinstance(item,(tuple,list)) else item for item in info.get('mismatched_keys',[])}
        unexpected=set(info.get('unexpected_keys',[]))
        if missing-allowed_missing or mismatched-{fixed_position} or info.get('error_msgs'):
            raise ValueError('Unexpected encoder mismatch; random encoder fallback forbidden')
        if any(not key.startswith('head.') for key in unexpected):raise ValueError('Unexpected public model weights')
        model.hf=loaded
        model.features.encoder=model.hf.model.encoder
        model.hf_config=cfg.to_dict()
        model.pretrained_identity={'model_id':MODEL_ID,'revision':REVISION,'files_sha256':identity,
            'execution':'official PatchTSTForPretraining.forward / PatchTSTModel.forward',
            'encoder_weights':'public forecasting encoder; fixed sincos positions regenerated by official code for native context',
            'task_head':'official mask reconstruction head, initialized for this task; NOT pretrained',
            'normalization':'official per-channel observed-window scaling, inverted for reconstruction',
            'input':'independent sensors as batch; native complete public-width patches; no interpolation',
            'expected_new_parameters':sorted(missing),'fixed_position_resize':sorted(mismatched)}
        model.configure_finetuning(1)
        return model

    def configure_finetuning(self,last_layers=1):
        layers=self.pretrained.encoder.layers
        if last_layers is not None and not 0<=last_layers<=len(layers):raise ValueError('Invalid official layer count')
        self.pretrained.requires_grad_(False);self.hf.head.requires_grad_(True)
        if last_layers is None:
            # Full source-domain adaptation, INCLUDING the pretrained embedder.
            self.pretrained.requires_grad_(True)
            positions=self.pretrained.encoder.positional_encoder
            if self.hf_config['positional_encoding_type']=='sincos':
                positions.position_enc.requires_grad_(False)
            return
        if last_layers:
            for layer in list(layers)[-last_layers:]:layer.requires_grad_(True)

    def train(self,mode=True):
        super().train(mode)
        # Keep frozen official BatchNorm running state fixed during head adaptation.
        for module in self.pretrained.modules():
            if not any(p.requires_grad for p in module.parameters()):module.eval()
        return self

    def _flat(self,x,mask=None):
        if x.ndim!=3 or x.shape[1]!=self.hf_config['context_length'] or not torch.isfinite(x).all():
            raise ValueError('Finite input with exact official native context required')
        batch,length,sensors=x.shape;patches=length//self.patch_len
        flat=x.transpose(1,2).reshape(batch*sensors,length,1)
        observed=torch.ones_like(flat,dtype=torch.bool)
        if mask is not None:
            if mask.shape!=(batch,sensors*patches):raise ValueError('Mask/native patch mismatch')
            hidden=mask.reshape(batch*sensors,patches).repeat_interleave(self.patch_len,dim=1)[...,None]
            flat=flat.masked_fill(hidden,0.);observed=~hidden
        return flat,observed,batch,sensors,patches

    def patchify(self,x):
        flat,_,batch,sensors,patches=self._flat(x)
        return self.features.patchifier(flat).reshape(batch,sensors*patches,self.patch_len),patches

    def _encode(self,x,mask=None):
        flat,observed,batch,sensors,patches=self._flat(x,mask)
        output=self.features(past_values=flat,past_observed_mask=observed,return_dict=True)
        return output,batch,sensors,patches

    def channel_independent_tokens(self,x,mask=None):
        output,batch,sensors,patches=self._encode(x,mask)
        hidden=output.last_hidden_state
        if self.hf_config['use_cls_token']:hidden=hidden[:,:,1:]
        return hidden.reshape(batch,sensors*patches,self.d_model)

    def tokens(self,x,mask=None):
        if x.shape[-1]!=self.n_sensors:raise ValueError('Use channel-independent adapter for external sensors')
        return self.channel_independent_tokens(x,mask)

    def channel_independent_forward(self,x,mask=None):
        output,batch,sensors,patches=self._encode(x,mask)
        pred=self.hf.head(output.last_hidden_state)
        # Official SSL head predicts normalized patches; residuals need input units.
        pred=pred*output.scale.unsqueeze(-1)+output.loc.unsqueeze(-1)
        return pred.reshape(batch,sensors*patches,self.patch_len)

    def forward(self,x,mask=None):
        if x.shape[-1]!=self.n_sensors:raise ValueError('Input sensor count mismatch')
        return self.channel_independent_forward(x,mask)

    def pretraining_loss(self,x,seed):
        flat,observed,_,_,_=self._flat(x)
        devices=[x.device.index if x.device.index is not None else torch.cuda.current_device()] if x.is_cuda else []
        with torch.random.fork_rng(devices=devices):
            torch.manual_seed(seed)
            return self.hf(past_values=flat,past_observed_mask=observed,return_dict=True).loss
